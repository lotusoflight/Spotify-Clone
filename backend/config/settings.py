# Database Configuration
# Primary: MySQL (for Managed Cloud MySQL or local MySQL)
# Configured via environment variables: MYSQL_DATABASE, MYSQL_USER, MYSQL_PASSWORD, MYSQL_HOST, MYSQL_PORT
USE_MYSQL = os.environ.get("USE_MYSQL", "True").lower() in ("true", "1")

if USE_MYSQL:
    db_options = {
        "charset": "utf8mb4",
    }
    # Cloud MySQL SSL Configuration (e.g. TiDB Cloud / Aiven)
    if os.environ.get("MYSQL_SSL_CA"):
        db_options["ssl"] = {"ca": os.environ["MYSQL_SSL_CA"]}
    elif os.environ.get("MYSQL_SSL_REQUIRED", "False").lower() in ("true", "1"):
        # Enables SSL encryption using OS root certificates (for TiDB Cloud Serverless)
        db_options["ssl"] = {}
    elif os.environ.get("MYSQL_SSL_DISABLED", "").lower() in ("true", "1"):
        db_options["ssl"] = {"disabled": True}

    DATABASES = {
        "default": {
            "ENGINE": "django.db.backends.mysql",
            "NAME": os.environ.get("MYSQL_DATABASE", "spotify_clone"),
            "USER": os.environ.get("MYSQL_USER", "root"),
            "PASSWORD": os.environ.get("MYSQL_PASSWORD", ""),
            "HOST": os.environ.get("MYSQL_HOST", "127.0.0.1"),
            "PORT": os.environ.get("MYSQL_PORT", "3306"),
            "OPTIONS": db_options,
            "CONN_MAX_AGE": 60,
        }
    }
else:
    DATABASES = {
        "default": {
            "ENGINE": "django.db.backends.sqlite3",
            "NAME": BASE_DIR / "db.sqlite3",
        }
    }


